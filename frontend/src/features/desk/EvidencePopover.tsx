import React, { useState } from 'react'
import { HelpCircle, X, ShieldCheck } from 'lucide-react'

interface EvidencePopoverProps {
  title?: string
  evidence: Record<string, any>
  rulesFired?: string[]
}

export default function EvidencePopover({
  title = 'Why am I seeing this?',
  evidence,
  rulesFired = [],
}: EvidencePopoverProps) {
  const [open, setOpen] = useState(false)

  if (!evidence || Object.keys(evidence).length === 0) return null

  return (
    <div className="relative inline-block">
      <button
        type="button"
        onClick={(e) => {
          e.stopPropagation()
          setOpen(!open)
        }}
        className="inline-flex items-center gap-1 text-xs text-brand-300 hover:text-brand-200 underline decoration-dotted transition-colors focus:outline-none"
        title="View deterministic calculation evidence"
      >
        <HelpCircle className="w-3.5 h-3.5" />
        <span>Why?</span>
      </button>

      {open && (
        <>
          <div
            className="fixed inset-0 z-40"
            onClick={(e) => {
              e.stopPropagation()
              setOpen(false)
            }}
          />
          <div
            className="absolute left-0 mt-2 w-80 bg-slate-900/95 backdrop-blur border border-slate-700/80 rounded-xl p-4 shadow-2xl z-50 text-left text-xs text-slate-300"
            onClick={(e) => e.stopPropagation()}
          >
            <div className="flex items-center justify-between pb-2 mb-2 border-b border-slate-800">
              <span className="font-semibold text-white flex items-center gap-1.5">
                <ShieldCheck className="w-4 h-4 text-emerald-400" />
                {title}
              </span>
              <button
                type="button"
                onClick={() => setOpen(false)}
                className="text-slate-400 hover:text-white p-0.5"
              >
                <X className="w-3.5 h-3.5" />
              </button>
            </div>

            {rulesFired.length > 0 && (
              <div className="mb-2.5">
                <div className="text-[11px] font-medium text-slate-400 uppercase tracking-wider mb-1">
                  Triggered Rule(s)
                </div>
                <div className="flex flex-wrap gap-1">
                  {rulesFired.map((r) => (
                    <span
                      key={r}
                      className="px-2 py-0.5 rounded-md bg-amber-500/10 text-amber-300 border border-amber-500/20 font-mono text-[10px]"
                    >
                      {r}
                    </span>
                  ))}
                </div>
              </div>
            )}

            <div className="space-y-1.5">
              <div className="text-[11px] font-medium text-slate-400 uppercase tracking-wider mb-1">
                Computed Numbers
              </div>
              {Object.entries(evidence).map(([k, v]) => {
                if (typeof v === 'object' && v !== null) return null
                return (
                  <div key={k} className="flex justify-between items-center py-0.5">
                    <span className="text-slate-400 capitalize">{k.replace(/_/g, ' ')}:</span>
                    <span className="font-mono text-slate-200 font-medium">
                      {typeof v === 'number'
                        ? k.includes('accuracy') || k.includes('mastery') || k.includes('drop') || k.includes('gain')
                          ? `${Math.round(v * 100)}%`
                          : v
                        : String(v)}
                    </span>
                  </div>
                )
              })}
            </div>

            <div className="mt-3 pt-2 border-t border-slate-800/80 text-[10px] text-slate-500 italic">
              Computed deterministically from session history, not generated by an LLM.
            </div>
          </div>
        </>
      )}
    </div>
  )
}
